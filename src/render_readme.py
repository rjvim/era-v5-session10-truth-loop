"""Regenerate the hardware-dependent part of README.md from its artifact.

Every other section of the README is prose about a result that reproduces
exactly, so it is written by hand and checked by `tests/test_readme_claims.py`.
Task 5 is different: it is wall-clock, so its numbers change on every run and
change completely if the repo moves to a GPU. Hand-writing that section means
it goes stale the moment anyone re-runs the benchmark, and the human then has
to transcribe a dozen figures correctly.

So it is generated instead. The block between the markers in README.md is
rewritten from `artifacts/t5_mfu.json`, and `run_all.py` calls this after Task 5
finishes. Running the benchmark on different hardware updates the prose, the
tables and the surrounding argument together, with no transcription step.

    python src/render_readme.py            # rewrite the block
    python src/render_readme.py --check    # fail if it is out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import ROOT, read_artifact

README = ROOT / "README.md"
TESTS = ROOT / "tests"
BEGIN = "<!-- BEGIN GENERATED: task5 -->"
END = "<!-- END GENERATED: task5 -->"


def test_counts() -> tuple[int, int]:
    """(test functions, collected cases). Parametrised tests expand, so these differ."""
    import re as _re
    import subprocess

    functions = sum(len(_re.findall(r"^def test_", f.read_text(), _re.M))
                    for f in sorted(TESTS.glob("test_*.py")))
    out = subprocess.run(
        [sys.executable, "-m", "pytest", str(TESTS), "--collect-only", "-q"],
        cwd=ROOT, capture_output=True, text=True,
    ).stdout
    m = _re.search(r"(\d+)\s+tests? collected", out)
    return functions, int(m.group(1)) if m else functions


def update_test_counts(text: str) -> str:
    """Keep the counts quoted in the README in step with the suite.

    Hand-maintaining these went wrong every single time a test was added, which
    is a small thing but exactly the kind of small thing this repo is about.
    """
    import re as _re

    functions, cases = test_counts()
    text = _re.sub(r"# \d+ passed", f"# {cases} passed", text)
    text = _re.sub(r"\d+ test functions, \d+ cases",
                   f"{functions} test functions, {cases} cases", text)
    return text


def render(t5: dict) -> str:
    h = t5["headline"]
    env = t5["environment"]
    rep = t5["repeatability"]
    b = t5["attribution"]["budget"]
    ph = t5["baseline"]["phase_fraction"]
    per_layer = [r["fraction_of_peak"] * 100
                 for r in t5["shape_efficiency"]["per_layer"]]
    ref = t5["instructor_v4_reference"]
    on_gpu = env["device"].startswith("cuda")

    peak = h["sustained_peak_gflops"]
    peak_str = (f"{peak / 1000:.1f} TFLOP/s" if peak >= 1000
                else f"{peak:.1f} GFLOP/s")
    hw = (f"{env.get('device_name', env['device'])}, {env['dtype'].split('.')[-1]}"
          if on_gpu else
          f"CPU, {env['dtype'].split('.')[-1]}, {env['torch_threads']} thread(s)")

    vendor = ""
    tp = t5.get("theoretical_peak")
    if tp and tp.get("vendor_peak_flops_per_s"):
        v = tp["vendor_peak_flops_per_s"] / 1e12
        ratio = (peak * 1e9) / tp["vendor_peak_flops_per_s"]
        vendor = (f" The vendor figure for this device is {v:.0f} TFLOP/s, so the "
                  f"benchmark sustains {ratio * 100:.0f}% of it; the headline below "
                  f"uses the measured number, which is the harder denominator.")

    sweep_rows = "\n".join(
        f"| {r['n_embd']} | {r['n_layer']} | {r['batch_rows']} | "
        f"{r['n_params'] / 1e6:.2f}M | "
        + (f"**{r['mfu_6N'] * 100:.1f}%**"
           if r["mfu_6N"] == h["best_sweep_mfu_6N"] else f"{r['mfu_6N'] * 100:.1f}%")
        + " |"
        for r in t5["size_sweep"]
    )

    # Which configuration first clears the 40% target. Sorting on parameter
    # count alone is not enough: two rows share each parameter count (B=8 and
    # B=32), so a naive scan produces "between 10.7M and 10.7M parameters".
    ordered = sorted(t5["size_sweep"], key=lambda r: (r["n_params"], r["batch_rows"]))
    clearing = [r for r in ordered if r["mfu_6N"] >= 0.40]
    if not clearing:
        cross_txt = ("without any tested configuration reaching 40%")
    elif len(clearing) == len(ordered):
        cross_txt = "above 40% at every size tested"
    else:
        f = clearing[0]
        cross_txt = (f"first clearing 40% at n_embd {f['n_embd']}, "
                     f"{f['n_layer']} layers, B={f['batch_rows']} "
                     f"({f['n_params'] / 1e6:.2f}M parameters)")

    return f"""{BEGIN}
<!-- Generated by src/render_readme.py from artifacts/t5_mfu.json. Do not edit
     by hand: re-run `python src/render_readme.py` after re-running Task 5. -->

`src/t5_mfu.py` → `artifacts/t5_mfu.json` · `figures/t5_mfu.png`

> **This is the one section of this repo that does not reproduce to the digit.** Every
> number here is a wall-clock measurement, so the prose below is generated from the
> artifact rather than typed, and the run-to-run spread is measured and quoted with the
> number instead of being hidden behind extra significant figures. Both the step timing
> and the GEMM benchmarks take the *fastest* of several passes, since contention on a
> shared machine can only ever make a timing slower.

Measured on **{hw}**.

Two choices keep the number from flattering itself.

**The denominator is measured, not quoted.** A spec-sheet peak is a marketing figure for
one dtype under one sparsity assumption. Here it is the best rate this machine sustains on
the fastest matmul in the training dtype, benchmarked in-process: **{peak_str}**, reached
on {t5['peak']['peak_at_label']}.{vendor}

The sweep deliberately includes the model's *own* GEMM shapes alongside large square ones.
Squares alone are not a safe denominator: a short wide matmul that fits in cache can beat
the biggest square one, and when it does, MFU is being divided by something that is not an
upper bound. The per-layer figures below are read from the same sweep that defines the
peak, so no layer can exceed it by construction — asserted in the tests. (This is not
hypothetical; see Limitations.)

**The numerator is reported under both conventions.** `6N` is what the brief asked for; it
undercounts, because attention's score and value matmuls involve no parameters at all, so
the PaLM-style `12·L·T·C` per token is given too. The headline uses the strict `6N` form.

| | |
|---|---|
| throughput | {h['tokens_per_second']:,.0f} tokens/s |
| **MFU (6N)**, best-of-3 timing pass | **{h['measured_mfu_6N'] * 100:.1f}%** |
| MFU (6N) across {rep['trials']} single-pass trials | **{h['mfu_6N_mean_over_trials'] * 100:.1f}% ± {h['mfu_6N_std_over_trials'] * 100:.1f}** (spread {h['mfu_6N_spread_pp']:.1f} pp) |
| MFU (6N + attention) | {h['measured_mfu_6N_plus_attention'] * 100:.1f}% |
| distance to 40% | {h['distance_to_40pct_pp']:.1f} pp |

The ± is not decoration. It is larger than several of the differences one might be tempted
to read into the table below, and it is why nothing in this section is quoted past one
decimal.

### Where the distance goes

| cause | cost | how it was measured |
|---|---|---|
| matmul shapes too small | {b['1_small_gemm_shapes']['mfu_lost_pp']:.1f} pp | the model's *actual* GEMM shapes benchmarked in isolation reach only **{b['1_small_gemm_shapes']['fraction_of_peak_reachable'] * 100:.1f}%** of the machine's large-GEMM rate |
| time not in matmuls | {b['2_time_not_spent_in_matmuls']['mfu_lost_pp']:.1f} pp | optimizer step {ph['optimizer'] * 100:.1f}% of a step, data prep {ph['data'] * 100:.1f}% |
| elementwise residual | {b['3_residual']['mfu_lost_pp']:.1f} pp | LayerNorm, GELU, softmax, causal mask, residual adds — counted by neither the `6N` model nor the GEMM benchmark |

**The third row is a remainder, not a measurement.** The first two terms come from
independent benchmarks — a GEMM run at the model's real shapes, and phase timing of the
step. The residual is defined as whatever is left over, so the arithmetic check that the
three sum to the measured MFU *cannot fail*, and the test asserting it is labelled in the
artifact as a coding check rather than evidence. The residual is only as trustworthy as
the claim that the first two terms are exhaustive, which I have not proved.

Per-layer shape efficiency runs {min(per_layer):.1f}% to {max(per_layer):.1f}% of that
ceiling. A step splits roughly {ph['forward'] * 100:.1f}% forward,
{ph['backward'] * 100:.1f}% backward, {ph['optimizer'] * 100:.1f}% optimizer.

### It is a size problem, not a code problem

| n_embd | L | B | params | MFU (6N) |
|---|---|---|---|---|
{sweep_rows}

MFU rises with both width and batch — a relationship far larger than the
±{h['mfu_6N_std_over_trials'] * 100:.1f} pp noise floor — {cross_txt}. The baseline's
~{h['measured_mfu_6N'] * 100:.0f}% is not inefficient code; it is a model too narrow to
keep the hardware busy, which is the same trade the session described from the other side:
the V4 run gave up MFU to buy RAM headroom through MoE and reversibility.

![MFU by model size, step time breakdown, per-layer GEMM efficiency](figures/t5_mfu.png)

### Recomputing the session's V4 number

The transcript is internally inconsistent: it reads *6848 teraflops achieved against 7912
peak* for *8.2% MFU*, and 6848/7912 is 87%. Recomputing from the stated model size and
throughput:

```
6 × 9e9 params × 12,000 tok/s = {ref['achieved_tflops_per_s']:.0f} TFLOP/s
{ref['achieved_tflops_per_s']:.0f} / 7,912 = {ref['mfu'] * 100:.2f}%        ← matches the 8.2% quoted
```

So the 6848 is a transcription slip for {ref['achieved_tflops_per_s']:.0f}, and the formula
reproduces his figure exactly.

{END}"""


def main() -> int:
    check = "--check" in sys.argv
    text = README.read_text()
    i, j = text.index(BEGIN), text.index(END) + len(END)
    new = render(read_artifact("t5_mfu.json"))
    updated = update_test_counts(text[:i] + new + text[j:])
    if updated == text:
        print("[readme] Task 5 section and test counts already up to date")
        return 0
    if check:
        print("[readme] README is STALE - run: python src/render_readme.py")
        return 1
    README.write_text(updated)
    print("[readme] regenerated the Task 5 section from artifacts/t5_mfu.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
